import { DEFAULT_PALETTE_ID, PALETTES, type Palette } from './palettes.ts';
import { TOKEN_NAMES, type Tokens } from './tokens.ts';

function block(selector: string, tokens: Tokens, colorScheme: 'light' | 'dark'): string {
  const lines = TOKEN_NAMES.map((name) => `  --${name}: ${tokens[name]};`);
  return `${selector} {\n  color-scheme: ${colorScheme};\n${lines.join('\n')}\n}`;
}

function paletteBlocks(p: Palette): string[] {
  const selectors = [`[data-palette='${p.id}']`];
  // The default palette also applies when no attribute is set (e.g. before JS runs).
  if (p.id === DEFAULT_PALETTE_ID) selectors.unshift(':root');
  const light = selectors.join(',\n');
  const dark = selectors.map((s) => (s === ':root' ? ':root.dark' : `.dark${s}`)).join(',\n');
  return [block(light, p.light, 'light'), block(dark, p.dark, 'dark')];
}

/** Exposes every token to Tailwind v4 as a color utility (`bg-primary`, `text-status-known`, …). */
function tailwindThemeBlock(): string {
  const lines = TOKEN_NAMES.map((name) => `  --color-${name}: var(--${name});`);
  return `@theme inline {\n${lines.join('\n')}\n}`;
}

/** Generates the Tailwind theme mapping plus custom-property blocks for every palette × mode. */
export function generatePalettesCss(): string {
  const header = '/* Generated by @alivocab/shared (gen:palettes-css). Do not edit. */';
  return `${[header, tailwindThemeBlock(), ...PALETTES.flatMap(paletteBlocks)].join('\n\n')}\n`;
}
